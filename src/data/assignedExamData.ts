import type { Exam, ExamQuestion } from "@/types/exam";

const OPTION_IDS = ["A", "B", "C", "D"];

function single(
  id: string,
  prompt: string,
  options: [string, string, string, string]
): ExamQuestion {
  return {
    id,
    type: "single",
    prompt,
    points: 2,
    options: options.map((text, index) => ({ id: OPTION_IDS[index], text })),
  };
}

